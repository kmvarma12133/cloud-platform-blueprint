#!/usr/bin/env python3
"""Generate Gatekeeper ConstraintTemplates from the Rego in platform/policies/rego.

The .rego files are the source of truth: they are unit-tested with `opa test`,
and each one carries its Gatekeeper kind and parameter schema in an OPA
`# METADATA` block. This script wraps every policy in a ConstraintTemplate and
embeds platform/policies/rego/lib/*.rego as `libs` when the policy imports it.

    python scripts/build-gatekeeper.py           # write templates
    python scripts/build-gatekeeper.py --check   # exit 1 if templates are stale (CI)
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGO_DIR = ROOT / "platform" / "policies" / "rego"
LIB_DIR = REGO_DIR / "lib"
OUT_DIR = ROOT / "platform" / "policies" / "gatekeeper" / "templates"
HEADER = "# Generated by scripts/build-gatekeeper.py from {src}. Do not edit by hand.\n"


def read_metadata(source: str, path: Path) -> dict:
    """Parse the first `# METADATA` comment block (YAML after the '# ' prefix)."""
    lines = source.splitlines()
    try:
        start = lines.index("# METADATA") + 1
    except ValueError:
        sys.exit(f"{path}: missing '# METADATA' block")
    block = []
    for line in lines[start:]:
        if not line.startswith("#"):
            break
        block.append(line[2:] if line.startswith("# ") else line[1:])
    meta = yaml.safe_load("\n".join(block)) or {}
    if "kind" not in meta.get("custom", {}):
        sys.exit(f"{path}: METADATA needs custom.kind (the Constraint kind)")
    return meta


def indent(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "".join(pad + line if line.strip() else line for line in text.splitlines(keepends=True))


def render(path: Path) -> str:
    source = path.read_text(encoding="utf-8")
    meta = read_metadata(source, path)
    kind = meta["custom"]["kind"]
    parameters = meta["custom"].get("parameters")

    schema = {"type": "object"}
    if parameters:
        schema["properties"] = parameters
    schema_yaml = yaml.safe_dump(
        {"openAPIV3Schema": schema}, sort_keys=False, default_flow_style=False
    )
    description = " ".join(meta.get("description", "").split())

    out = HEADER.format(src=path.relative_to(ROOT).as_posix())
    out += "apiVersion: templates.gatekeeper.sh/v1\n"
    out += "kind: ConstraintTemplate\n"
    out += "metadata:\n"
    out += f"  name: {kind.lower()}\n"
    out += "  annotations:\n"
    # json.dumps yields a valid double-quoted YAML scalar.
    out += f"    metadata.gatekeeper.sh/title: {json.dumps(meta.get('title', kind))}\n"
    out += f"    description: {json.dumps(description)}\n"
    # Templates must exist (and their CRDs be established) before Constraints.
    out += '    argocd.argoproj.io/sync-wave: "0"\n'
    out += "spec:\n"
    out += "  crd:\n"
    out += "    spec:\n"
    out += "      names:\n"
    out += f"        kind: {kind}\n"
    out += "      validation:\n"
    out += indent(schema_yaml, 8)
    out += "  targets:\n"
    out += "    - target: admission.k8s.gatekeeper.sh\n"
    # The policies are Rego v1. Gatekeeper parses the legacy `rego` field as v0
    # and only allows data.lib/data.inventory imports there, so it rejects
    # `import rego.v1`; the `code` source with version v1 is the supported form.
    out += "      code:\n"
    out += "        - engine: Rego\n"
    out += "          source:\n"
    out += '            version: "v1"\n'
    out += "            rego: |\n"
    out += indent(strip_v1_import(source), 14)
    if "import data.lib." in source:
        out += "            libs:\n"
        for lib in sorted(LIB_DIR.glob("*.rego")):
            if lib.name.endswith("_test.rego"):
                continue
            out += "              - |\n"
            out += indent(strip_v1_import(lib.read_text(encoding="utf-8")), 16)
    return out


def strip_v1_import(source: str) -> str:
    """Drop `import rego.v1`: opa test needs it, v1 mode makes it redundant."""
    return "".join(
        line for line in source.splitlines(keepends=True) if line.strip() != "import rego.v1"
    )


def build() -> dict[Path, str]:
    policies = sorted(p for p in REGO_DIR.glob("*.rego") if not p.name.endswith("_test.rego"))
    outputs = {OUT_DIR / f"{read_kind(p)}.yaml": render(p) for p in policies}
    resources = "".join(f"  - {p.name}\n" for p in sorted(outputs))
    outputs[OUT_DIR / "kustomization.yaml"] = (
        HEADER.format(src="platform/policies/rego")
        + "apiVersion: kustomize.config.k8s.io/v1beta1\n"
        + "kind: Kustomization\n"
        + "resources:\n"
        + resources
    )
    return outputs


def read_kind(path: Path) -> str:
    return read_metadata(path.read_text(encoding="utf-8"), path)["custom"]["kind"].lower()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if templates are out of date")
    args = parser.parse_args()

    outputs = build()
    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        stale.append(path)
        if args.check:
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=f"{path.relative_to(ROOT).as_posix()} (committed)",
                    tofile=f"{path.relative_to(ROOT).as_posix()} (generated)",
                )
            )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    orphans = [p for p in OUT_DIR.glob("*.yaml") if p not in outputs]
    if args.check:
        for orphan in orphans:
            print(f"{orphan.relative_to(ROOT).as_posix()}: no matching .rego source")
        if stale or orphans:
            print("\nGatekeeper templates are stale. Run: python scripts/build-gatekeeper.py")
            return 1
        print(f"Gatekeeper templates are up to date ({len(outputs) - 1} templates).")
        return 0

    for orphan in orphans:
        orphan.unlink()
    out_dir = OUT_DIR.relative_to(ROOT).as_posix()
    print(f"Wrote {len(stale)} file(s), removed {len(orphans)} orphan(s) in {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
